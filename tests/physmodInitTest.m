function tests = physmodInitTest
% Model initialization, regression and calibration tests for different
% combinations of physics submodels (port of the python package's
% test_physmod_init.py).
tests = functiontests(localfunctions);
end

function setup(tc)
addProjectRootToPath(tc);
tc.TestData.h = physicsTestHelpers();
tc.TestData.ptwParams = struct('theta', 0.1, 'p', 2, 's0', 0.02, 'sInf', 0.01, ...
    'kappa', 0.3, 'lgamma', -12, 'y0', 0.01, 'yInf', 0.003, 'y1', 0.09, 'y2', 0.7);
end

function checkModel(tc, models, params, consts, baselineFile, constraint, seed)
% regression test against the python baseline, then a pooled calibration
% whose best draws must be within 1% of the generating values
h = tc.TestData.h;
mm = physics.MaterialModel(flow_stress_model=models{1}, melt_model=models{2}, ...
    shear_modulus_model=models{3}, specific_heat_model=models{4}, ...
    density_model=models{5});
res = h.run(mm, params, consts, 0.6, 2500e-6, 100, 1000);
strains = res(:, 2);
stresses = res(:, 3);
tc.verifyEqual([strains stresses], h.baseline(baselineFile), ...
    'AbsTol', 1e-8, 'RelTol', 1e-5);

rng(seed);
out = h.calibrate(params, consts, strains, stresses, models, constraint);
fn = fieldnames(out.theta_native);
tc.verifyEqual(sort(fn), sort(fieldnames(params)));
for i = 1:numel(fn)
    v = out.theta_native.(fn{i});
    tc.verifyLessThan(min(abs(v/params.(fn{i}) - 1)), 1e-2, fn{i});
end
end

