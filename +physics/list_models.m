function out = list_models()
% Lists the available physics submodels, grouped by the MaterialModel
% argument they can be passed to (the MATLAB counterpart of
% getoptions_ModelMaterialStrength in the python package)
%
% returns a struct with fields flow_stress_model, melt_model, shear_model,
% specific_heat_model, density_model and heating_model, each a cell array
% of submodel names
out.flow_stress_model = {'Constant_Yield_Stress', 'JC_Yield_Stress', ...
    'PTW_Yield_Stress', 'Stein_Flow_Stress'};
out.melt_model = {'Constant_Melt_Temperature', 'Linear_Melt_Temperature', ...
    'Quadratic_Melt_Temperature', 'Cubic_Melt_Temperature', ...
    'BGP_Melt_Temperature'};
out.shear_model = {'Constant_Shear_Modulus', 'Linear_Cold_PW_Shear_Modulus', ...
    'Quadratic_Cold_PW_Shear_Modulus', 'Simple_Shear_Modulus', ...
    'BGP_PW_Shear_Modulus', 'Stein_Shear_Modulus'};
out.specific_heat_model = {'Constant_Specific_Heat', 'Linear_Specific_Heat', ...
    'Quadratic_Specific_Heat', 'Cubic_Specific_Heat', ...
    'Piecewise_Linear_Specific_Heat', 'Piecewise_Quadratic_Specific_Heat', ...
    'Piecewise_Cubic_Specific_Heat'};
out.density_model = {'Constant_Density', 'Linear_Density', ...
    'Quadratic_Density', 'Cubic_Density'};
out.heating_model = {'Taylor_Quinney_Heating'};
end
